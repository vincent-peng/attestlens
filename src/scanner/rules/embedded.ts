function ruleFromHeaderCheck(check: (typeof HEADER_CHECKS)[number]): RuleDefinition {
  return {
    id: check.id,
    category: 'url-headers',
    severity: check.severity,
    title: check.title,
    description: check.description,
    fixPrompt: check.fixPrompt,
    appMappings: [app11Mapping],
    addedIn: EMBEDDED_RULE_PACK_VERSION,
    enabled: true,
    tags: ['url-scan', 'headers', check.header],
  };
}

function ruleFromInfraCheck(check: (typeof INFRA_CHECKS)[number]): RuleDefinition {
  return {
    id: check.id,
    category: 'url-infra',
    severity: check.severity,
    title: check.title,
    description: check.description,
    pattern: check.contentPatterns?.map((pattern) => pattern.source).join('|'),
    flags: check.contentPatterns?.some((pattern) => pattern.flags.includes('i')) ? 'i' : undefined,
    fixPrompt: check.fixPrompt,
    appMappings: check.appMappings,
    addedIn: EMBEDDED_RULE_PACK_VERSION,
    enabled: true,
    tags: ['url-scan', 'infra', check.path],
  };
}

function ruleFromKeyPattern(pattern: (typeof KEY_PATTERNS)[number]): RuleDefinition {
  return {
    id: pattern.id,
    category: 'exposed-keys',
    severity: pattern.severity,
    title: pattern.title,
    description: pattern.description,
    pattern: pattern.pattern.source,
    flags: pattern.pattern.flags,
    fixPrompt: pattern.fixPrompt,
    appMappings: pattern.appMappings,
    addedIn: EMBEDDED_RULE_PACK_VERSION,
    enabled: true,
    tags: ['url-scan', 'secret', pattern.name],
  };
}

